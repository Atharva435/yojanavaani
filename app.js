function speakAssistantReply(text) {
  if (!("speechSynthesis" in window) || !("SpeechSynthesisUtterance" in window)) {
    showToast(t("assistant_speech_unavailable"));
    return;
  }
  const voiceLocale = LANGUAGES.find(([code]) => code === language)?.[2] || "en-IN";
  const voices = window.speechSynthesis.getVoices();
  const voice = voices.find(item => item.lang.toLowerCase() === voiceLocale.toLowerCase())
    || voices.find(item => item.lang.toLowerCase().startsWith(`${language}-`));
  if (!voice) {
    showToast(t("assistant_speech_unavailable"));
    return;
  }
  window.speechSynthesis.cancel();
  const utterance = new SpeechSynthesisUtterance(text);
  utterance.lang = voiceLocale;
  utterance.voice = voice;
  window.speechSynthesis.speak(utterance);
}

