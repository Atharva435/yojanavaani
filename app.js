function schemeEligibilityLabels(scheme) {
  const rules = scheme.rules;
  const criteria = [];
  if (rules.min_age !== null && rules.max_age !== null) {
    criteria.push(`${t("catalog_age")}: ${rules.min_age}–${rules.max_age} ${t("years")}`);
  } else if (rules.min_age !== null) {
    criteria.push(`${t("catalog_age")}: ${rules.min_age}+ ${t("years")}`);
  } else if (rules.max_age !== null) {
    criteria.push(`${t("catalog_age")}: up to ${rules.max_age} ${t("years")}`);
  }
  if (rules.required_occupation) {
    criteria.push(t(rules.required_occupation) || rules.required_occupation);
  }
  if (rules.required_gender) {
    criteria.push(t(`catalog_gender_${rules.required_gender}`) || rules.required_gender);
  }
  if (rules.requires_land) criteria.push(t("catalog_land"));
  if (rules.requires_no_lpg) criteria.push(t("catalog_no_lpg"));
  if (rules.requires_bank_account) criteria.push(t("catalog_bank"));
  if (rules.requires_student) criteria.push(t("catalog_student"));
  if (rules.manual_verification) criteria.push(t("catalog_manual"));
  if (!criteria.length) criteria.push(t("catalog_verified"));
  return criteria;
}

