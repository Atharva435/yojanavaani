function speechLanguage() {
  return LANGUAGES.find(([code]) => code === language)?.[2] || "en-IN";
}

function speak(text) {
  if (!("speechSynthesis" in window)) return Promise.resolve();
  return new Promise(resolve => {
    window.speechSynthesis.cancel();
    const utterance = new SpeechSynthesisUtterance(text);
    utterance.lang = speechLanguage();
    utterance.rate = 0.92;
    utterance.onend = resolve;
    utterance.onerror = resolve;
    window.speechSynthesis.speak(utterance);
  });
}

function listenOnce() {
  const Recognition = window.SpeechRecognition || window.webkitSpeechRecognition;
  if (!Recognition) return Promise.reject(new Error(t("voice_unsupported")));
  return new Promise((resolve, reject) => {
    const recognition = new Recognition();
    recognition.lang = speechLanguage();
    recognition.interimResults = false;
    recognition.maxAlternatives = 1;
    recognition.onresult = event => resolve(event.results[0][0].transcript);
    recognition.onerror = event => reject(new Error(event.error === "no-speech" ? t("voice_not_heard") : event.error));
    recognition.onend = () => {};
    recognition.start();
  });
}

function matchOption(select, words) {
  const normalized = words.toLocaleLowerCase();
  const candidates = [...select.options].filter(option => option.value);
  const found = candidates.find(option => normalized.includes(option.textContent.toLocaleLowerCase()) || normalized.includes(option.value));
  if (found) select.value = found.value;
}

function setVoiceValue(name, transcript) {
  const normalized = transcript.toLocaleLowerCase();
  const control = form.elements[name];
  if (!control) return;
  if (control.type === "checkbox") {
    control.checked = /yes|yeah|yep|हो|हाँ|हां|होय|आहे|असत|yes/i.test(normalized);
    return;
  }
  if (control.tagName === "SELECT") {
    if (name === "state") {
      const state = stateOptions.find(item => normalized.includes(item.toLocaleLowerCase()));
      if (state) control.value = state;
      return;
    }
    const aliases = {
      gender: {woman:["woman","female","महिला","औरत","स्त्री"],man:["man","male","पुरुष"],other:["other","अन्य","इतर"],prefer_not_to_say:["prefer not","नहीं बताना","सांगू इच्छित नाही"]},
      category: {general:["general","सामान्य"],sc:["sc","एससी"],st:["st","एसटी"],obc:["obc","ओबीसी"],other:["other","अन्य","इतर"],prefer_not_to_say:["prefer not","नहीं बताना","सांगू इच्छित नाही"]},
      occupation: {farmer:["farmer","किसान","शेतकरी"],student:["student","विद्यार्थी"],worker:["worker","कामगार"],other:["other","अन्य","इतर"]}
    };
    for (const [value, words] of Object.entries(aliases[name] || {})) {
      if (words.some(word => normalized.includes(word))) { control.value = value; return; }
    }
    matchOption(control, transcript);
    return;
  }
  const numeral = normalized.match(/\d[\d,]*(?:\.\d+)?/);
  if (!numeral) return;
  let value = Number(numeral[0].replaceAll(",", ""));
  if (name === "annual_income" && /lakh|लाख/i.test(normalized)) value *= 100000;
  control.value = String(Math.round(value));
}

async function voiceCheck() {
  if (!(window.SpeechRecognition || window.webkitSpeechRecognition)) {
    showToast(t("voice_unsupported"));
    return;
  }
  const prompts = [
    ["age","ask_age"],["state","ask_state"],["annual_income","ask_income"],
    ["gender","ask_gender"],["category","ask_category"],["occupation","ask_occupation"],
    ["owns_land","ask_land"],["is_student","ask_student"],["has_lpg","ask_lpg"],
    ["has_bank_account","ask_bank"],["is_taxpayer","ask_tax"]
  ];
  const button = document.getElementById("voice-start");
  button.disabled = true;
  const originalLabel = button.innerHTML;
  button.querySelector("[data-i18n='voice_start']").textContent = language === "en" ? "Listening… say “stop” to cancel" : "ऐकत आहे… थांबण्यासाठी सांगा";
  try {
    await speak(t("voice_instructions"));
    for (const [field, prompt] of prompts) {
      if (window.__yvStopVoice) break;
      await speak(t(prompt));
      const answer = await listenOnce();
      if (/^(stop|cancel|बस|रुको|थांबा|बंद)$/i.test(answer.trim())) {
        showToast(t("voice_cancel"));
        break;
      }
      setVoiceValue(field, answer);
    }
    if (!window.__yvStopVoice) {
      showToast(t("voice_done"));
      form.scrollIntoView({behavior:"smooth", block:"start"});
    }
  } catch (error) {
    showToast(error.message === "aborted" ? t("voice_cancel") : error.message);
  } finally {
    window.__yvStopVoice = false;
    button.disabled = false;
    button.innerHTML = originalLabel;
  }
}

