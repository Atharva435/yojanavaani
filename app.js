async function initializeFirebaseAuth() {
  const appSdk = await import("https://www.gstatic.com/firebasejs/11.6.0/firebase-app.js");
  firebaseAuthSdk = await import("https://www.gstatic.com/firebasejs/11.6.0/firebase-auth.js");
  const firebaseApp = appSdk.initializeApp(firebaseConfig);
  firebaseAuth = firebaseAuthSdk.getAuth(firebaseApp);
  await firebaseAuthSdk.setPersistence(firebaseAuth, firebaseAuthSdk.browserSessionPersistence);
  return await new Promise(resolve => {
    let unsubscribe = () => {};
    unsubscribe = firebaseAuthSdk.onAuthStateChanged(firebaseAuth, user => {
      unsubscribe();
      resolve(user);
    }, () => resolve(null));
  });
}

