async function initialize() {
  applyLanguage();
  try {
    const [config, session] = await Promise.all([
      api("/api/auth/config"),
      api("/api/auth/me")
    ]);
    firebaseConfig = config.firebase_configured ? config.firebase : null;
    assistantConfigured = Boolean(config.assistant_configured);
    document.getElementById("firebase-methods").hidden = !firebaseConfig;
    document.getElementById("firebase-setup").hidden = Boolean(firebaseConfig);
    let loginMessage = "";
    let existingUser = null;
    if (firebaseConfig) {
      try {
        existingUser = await initializeFirebaseAuth();
      } catch (error) {
        loginMessage = error.message || "Mobile-number sign-in could not be initialized.";
      }
    }
    if (session.authenticated && session.user) {
      await showAuthenticatedApp(session.user);
      return;
    }
    if (existingUser) {
      try {
        await authenticateFirebaseUser(existingUser);
        return;
      } catch (error) {
        loginMessage = error.message || t("login_failed");
      }
    }
    showLoginScreen(loginMessage);
  } catch (error) {
    showLoginScreen(error.message || "Could not connect to the local YojanaVaani server.");
  }
}

